"""Arabic translations for ags_edusmart.

Source of truth for ``translations/ar.csv``, which is generated from here by
``tools/build_translations.py``. Kept as Python rather than edited as raw CSV so
the terminology decisions can carry their reasoning.

Terminology decisions worth recording, because they are the ones a second
translator would otherwise undo:

* **The "AGS" prefix is dropped in Arabic.** "AGS Campus" becomes الحرم المدرسي,
  not "حرم AGS". Inside the AGS system the brand is redundant, and mixing Latin
  and Arabic in one label is precisely the bidi hazard documented in
  ``utils/formatting.py``.
* **School Division → المرحلة الدراسية** (educational *stage*), not القسم.
  ERPNext already uses القسم for Department, and the AGS divisions genuinely are
  stages: Kindergarten, Primary, Middle, Secondary.
* **Payer Account → حساب الدافع**, deliberately not حساب ولي الأمر. The whole
  point of the entity (SKILL sec. 13.4) is that the payer is *not* necessarily
  the guardian; translating it as "guardian account" would erase the
  distinction the data model exists to preserve.
* **Commitment → ارتباط**, the standard term in Arabic public-sector budgeting
  for an amount reserved but not yet spent.
* **Identifiers are not translated.** Naming series (AGS-PAY-.#####), language
  codes, "SQL", "UOM", "UUID" and provider names stay verbatim; translating them
  would break the values they name.
"""

